import { readFile, writeFile } from 'node:fs/promises';
import { createMetricTools } from './metrics.js';

// Controlled prebuilt JavaScript adapter, not a general-purpose ESM compiler.
let source = await readFile(new URL('./client-entry.js', import.meta.url), 'utf8');
const react = "import * as React from 'react';";
if (!source.startsWith(react) || source.split('/*__METRIC_TOOLS__*/').length !== 2) throw new Error('Unexpected client source contract');
source = source.slice(react.length).replace('/*__METRIC_TOOLS__*/', createMetricTools.toString());
const names = [...source.matchAll(/^export\s+(?:async\s+)?(?:function|const|class)\s+([A-Za-z_$][\w$]*)/gm)].map(match => match[1]);
if (!names.includes('inject') || !names.includes('apply')) throw new Error('Missing native client plugin exports');
source = source.replace(/^export\s+/gm, '');
if (/^\s*(?:import|export)\b/m.test(source)) throw new Error('Unsupported client module syntax');
const artifact = `// Generated by build.mjs; uses the host React instance only.\nwindow.__ModuleLoader__.load({id:'@local/dsh-usage-dashboard',factory(require){\n'use strict';\nconst React=require('react');\n${source}\nreturn {${names.join(',')}};\n}});\n`;
await writeFile(new URL('./client.js', import.meta.url), artifact);
console.log('Built native ModuleLoader artifact; exactly one provided React import, no private client package imports.');
